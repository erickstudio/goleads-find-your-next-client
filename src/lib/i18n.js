export function normalizeLanguage(raw) {
  if (!raw || typeof raw !== "string") return null;
  const clean = raw.trim().toLowerCase();
  if (clean.startsWith("es")) return "es";
  if (clean.startsWith("en")) return "en";
  return null;
}

export function detectBrowserLanguage() {
  if (typeof navigator === "undefined") return "en";
  const candidates = [
    ...(Array.isArray(navigator.languages) ? navigator.languages : []),
    navigator.language,
  ];
  for (const cand of candidates) {
    const matched = normalizeLanguage(cand);
    if (matched) return matched;
  }
  return "en";
}

export function translate(lang = "en", keyPath = "", vars = {}) {
  const safeLang = SUPPORTED_LANGUAGES.includes(lang) ? lang : "en";
  const parts = String(keyPath).split(".");
  let current = TRANSLATIONS[safeLang];
  for (const part of parts) {
    if (current && typeof current === "object" && part in current) {
      current = current[part];
    } else {
      current = null;
      break;
    }
  }
  if (typeof current !== "string") {
    let fallback = TRANSLATIONS.en;
    for (const part of parts) {
      if (fallback && typeof fallback === "object" && part in fallback) {
        fallback = fallback[part];
      } else {
        fallback = null;
        break;
      }
    }
    current = typeof fallback === "string" ? fallback : keyPath;
  }

  return current.replace(/\{(\w+)\}/g, (_, token) =>
    vars[token] !== undefined && vars[token] !== null ? String(vars[token]) : `{${token}}`
  );
}

/**
 * Generates an evidence-grounded outreach draft in the explicitly chosen outreachLanguage
 * ('en' or 'es'), independent of the current UI language.
 */
export function buildOutreachDraft(opportunity, selectedServices = [], serviceDescription = "", outreachLang = "en") {
  const biz = opportunity?.business_name || (outreachLang === "es" ? "su equipo" : "your team");
  const loc = opportunity?.location || "";
  const signal = opportunity?.signal_type || (outreachLang === "es" ? "apertura o expansión" : "opening or expansion");
  const sourceTitle = opportunity?.source_title || (outreachLang === "es" ? "la publicación reciente" : "the recent announcement");
  const servicesList =
    Array.isArray(selectedServices) && selectedServices.length > 0
      ? selectedServices.join(", ")
      : outreachLang === "es"
      ? "servicios profesionales para negocios en crecimiento"
      : "professional services for expanding businesses";
  const extraOffer = serviceDescription ? ` (${serviceDescription.trim()})` : "";

  if (outreachLang === "es") {
    return `Hola equipo de ${biz},\n\nVi la nota en ${sourceTitle} sobre su ${signal.toLowerCase()}${loc ? ` en ${loc}` : ""}.\n\nApoyamos a negocios en etapa de apertura o expansión con ${servicesList}${extraOffer}. Si están evaluando proveedores externos para esta etapa, ¿les parecería útil que les comparta un par de ideas concretas adaptadas a su lanzamiento?\n\nSaludos cordiales,`;
  }

  return `Hi ${biz} team,\n\nI saw the coverage in ${sourceTitle} regarding your ${signal.toLowerCase()}${loc ? ` in ${loc}` : ""}.\n\nWe help newly opening and expanding businesses with ${servicesList}${extraOffer}. If you are evaluating external partners as you set up this location, would it be helpful if I shared a brief outline of how we support launches like yours?\n\nBest regards,`;
}